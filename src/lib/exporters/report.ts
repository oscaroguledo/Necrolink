/**
 * Resurrection report (spec 04, phase 5): a Markdown summary of every link
 * and its fix. The export for PDFs, which are not rewritten.
 */

import type { CheckResult, ExtractedLink } from '@/types/link';
import { escapeMarkdown } from './markdown';
import { isArchiveUrl, NECROLINK_URL } from './replacement-map';

type LinkInfo = Pick<ExtractedLink, 'id' | 'originalUrl'> & Partial<Pick<ExtractedLink, 'text' | 'position'>>;
type ResultInfo = Pick<CheckResult, 'linkId' | 'status' | 'reason' | 'archived'>;

const cell = (text: string) => escapeMarkdown(text.replace(/\s+/g, ' ').trim()).slice(0, 300) || ' ';
/** URL in angle brackets: an autolink that can't break the table or inject Markdown. */
const urlCell = (url: string) => `<${encodeURI(decodeSafe(url)).replace(/[<>|]/g, encodeURIComponent)}>`;

function decodeSafe(url: string): string {
  try {
    return decodeURI(url);
  } catch {
    return url;
  }
}

function where(link: LinkInfo): string {
  if (link.position?.page) return `p. ${link.position.page}`;
  if (link.position?.line) return `line ${link.position.line}`;
  return '–';
}

export function exportReport(
  filename: string,
  links: LinkInfo[],
  results: ResultInfo[],
  now: Date = new Date()
): string {
  const byId = new Map(results.map((r) => [r.linkId, r]));
  const rows = links.map((link) => ({ link, result: byId.get(link.id) }));
  const of = (status: string) => rows.filter((r) => r.result?.status === status);

  const ghosts = of('ghost').filter((r) => isArchiveUrl(r.result?.archived?.url));
  const zombies = of('zombie');
  const lost = of('lost');
  const living = of('living');
  const unchecked = rows.filter((r) => !r.result || r.result.status === 'error');

  const lines: string[] = [
    `# 🪦 Necrolink report: ${escapeMarkdown(filename)}`,
    '',
    `Checked ${now.toISOString().slice(0, 10)} · ${links.length} links · ` +
      `👻 ${ghosts.length} resurrected · 🧟 ${zombies.length} zombies · 🪦 ${lost.length} lost · 🕯️ ${living.length} living`,
  ];

  if (ghosts.length) {
    lines.push('', '## 👻 Ghosts: dead, resurrected from the Internet Archive', '', '| Where | Link text | Original | Archived copy |', '|---|---|---|---|');
    for (const { link, result } of ghosts) {
      const date = result!.archived!.timestamp?.slice(0, 10) ?? 'copy';
      lines.push(`| ${where(link)} | ${cell(link.text ?? '')} | ${urlCell(link.originalUrl)} | [${date}](${urlCell(result!.archived!.url).slice(1, -1)}) |`);
    }
  }
  if (zombies.length) {
    lines.push('', '## 🧟 Zombies: still load, but the content changed', '', '| Where | Link text | URL | What changed |', '|---|---|---|---|');
    for (const { link, result } of zombies) {
      const copy = isArchiveUrl(result!.archived?.url) ? ` [Cited version](${urlCell(result!.archived!.url).slice(1, -1)})` : '';
      lines.push(`| ${where(link)} | ${cell(link.text ?? '')} | ${urlCell(link.originalUrl)} | ${cell(result!.reason)}${copy} |`);
    }
  }
  if (lost.length) {
    lines.push('', '## 🪦 Lost souls: dead, no archived copy (find another source)', '', '| Where | Link text | URL | Why |', '|---|---|---|---|');
    for (const { link, result } of lost) {
      lines.push(`| ${where(link)} | ${cell(link.text ?? '')} | ${urlCell(link.originalUrl)} | ${cell(result!.reason)} |`);
    }
  }
  if (unchecked.length) {
    lines.push('', `## Not checked (${unchecked.length})`, '');
    for (const { link, result } of unchecked) {
      lines.push(`- ${urlCell(link.originalUrl)}: ${cell(result?.reason ?? 'No result')}`);
    }
  }
  lines.push('', `## 🕯️ Living: ${living.length} links still work`, '', '---', '', `*Generated by [Necrolink](${NECROLINK_URL}).*`, '');
  return lines.join('\n');
}
